run <- function(label, brts, pars, model, link, n=2000L, rho=1) {
  cnt(TRUE); ok <- TRUE
  raw <- tryCatch(emphasis:::augment_trees(brts=brts, pars=pars, sample_size=n, maxN=50L*n, max_missing=500L,
                     max_lambda=1e6, num_threads=1L, model=model, link=link, rho=rho), error=function(e) {ok <<- FALSE; conditionMessage(e)})
  if (!ok) { cat(sprintf("%-42s link=%d ERROR %s\n", label, link, raw)); return(invisible()) }
  nm <- vapply(raw$trees, function(d) sum(!(d$t_ext == 0 | d$t_ext == 1e11 | d$t_ext == 5e10)), 1)
  v <- cnt()
  cat(sprintf("%-42s link=%d | ntrees=%d rej(ov/lam/zw)=%d/%d/%d | mean#miss %.2f | VIOLATIONS=%d (%.4f per tree)\n",
              label, link, length(raw$trees), raw$rejected_overruns, raw$rejected_lambda, raw$rejected_zero_weights, mean(nm), v, v/length(raw$trees)))
}
