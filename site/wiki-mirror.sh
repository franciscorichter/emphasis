#!/bin/bash
# Mirror the experiments wiki (the Forgejo wiki of pancho/emphasis-paper) to the GitHub wiki of
# franciscorichter/emphasis, through the public filter (site/public.py: the When and Where rows
# dropped, forge links reduced to file names, and a refusal on any private token), so the public
# wiki is a copy of the record and never edited by hand.
#   site/wiki-mirror.sh <path to the wiki checkout> [commit message]
# GitHub creates the wiki repository when its first page is made in the browser; until then the
# push fails with "repository not found".
set -e
SRC=${1:?wiki checkout}; MSG=${2:-"mirror of the experiments wiki $(date +%F)"}
HERE=$(cd "$(dirname "$0")" && pwd)
TMP=$(mktemp -d)
git clone -q https://github.com/franciscorichter/emphasis.wiki.git "$TMP/wiki"
cd "$TMP/wiki"
find . -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
fail=0
for f in "$SRC"/*.md; do
  python3 "$HERE/public.py" --filter "$f" "./$(basename "$f")" || fail=1
done
if [ "$fail" = 1 ]; then echo "wiki mirror refused: private tokens remain (listed above)"; rm -rf "$TMP"; exit 1; fi
mkdir -p images && cp "$SRC"/images/*.png images/
cat > _Footer.md <<'EOF'
This wiki is a copy of the experiments record kept with the `emphasis-paper` repository, regenerated by `site/wiki-mirror.sh` and not edited here. The package and its documentation: <https://franciscorichter.github.io/emphasis/>.
EOF
git add -A
if git diff --cached --quiet; then echo "wiki mirror: nothing to update"; else
  git -c user.name="franciscorichter" -c user.email="franciscorichter@gmail.com" commit -q -m "$MSG"
  git push -q origin HEAD && echo "wiki mirror pushed: $(git log --oneline -1)"
fi
rm -rf "$TMP"
